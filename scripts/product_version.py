"""Validate or synchronize generated versions from release.json (dry-run by default)."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
VERSION_FILES = ['app/package.json', 'app/package-lock.json', 'app/src-tauri/Cargo.toml',
                 'app/src-tauri/Cargo.lock', 'app/src-tauri/tauri.conf.json']
PROFILES = {
    'preview': {'identifier': 'com.account.preview', 'desktopConfig': 'AccountPreview',
                'productName': 'Account Preview',
                'platforms': ['windows-x64', 'macos-arm64', 'macos-x64', 'android-arm64']},
    'personal': {'identifier': 'com.account.probe', 'desktopConfig': 'AccountDesktop',
                 'productName': 'Account', 'platforms': ['windows-x64', 'android-arm64']},
}


def version_key(value):
    if not isinstance(value, str): raise ValueError('版本须为字符串。')
    match = re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)-preview\.([1-9]\d*)', value or '')
    if not match: raise ValueError('版本须为 X.Y.Z-preview.N。')
    return tuple(map(int, match.groups()))


def native_key(value):
    if not isinstance(value,str): raise ValueError('原生安装版本须为 X.Y.Z。')
    match=re.fullmatch(r'(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)',value)
    if not match: raise ValueError('原生安装版本须为 X.Y.Z。')
    return tuple(map(int,match.groups()))


def validate(data, previous=None):
    if not isinstance(data, dict): raise ValueError('release.json 须为对象。')
    key = version_key(data.get('version'))
    native = native_key(data.get('nativeVersion'))
    if data.get('tag') != 'v' + data['version'] or native < key[:3]:
        raise ValueError('tag 须匹配产品版本，原生安装版本不得早于产品系列。')
    if data.get('channel') != 'private-preview' or data.get('repository') != 'Milozpace/Account-Preview':
        raise ValueError('发布来源或频道无效。')
    code = data.get('androidVersionCode')
    minimum_code = key[0]*1_000_000 + key[1]*1_000 + key[2]
    if type(code) is not int or not minimum_code <= code <= 2_100_000_000 or code <= 0:
        raise ValueError('Android versionCode 必须是有效正整数。')
    if data.get('profiles') != PROFILES: raise ValueError('安装身份或支持平台与固定档案不符。')
    if previous:
        old = version_key(previous['version'])
        if key < old: raise ValueError('拒绝版本降级。')
        old_native=native_key(previous['nativeVersion'])
        if key == old and (native != old_native or code != previous['androidVersionCode']):
            raise ValueError('同一版本不可重用为不同安装版本。')
        if key > old and (native <= old_native or code <= previous['androidVersionCode']):
            raise ValueError('新安装版本的 nativeVersion 和 Android versionCode 均必须严格增加。')
    return data


def load(root=ROOT):
    return validate(json.loads((Path(root)/'release.json').read_text(encoding='utf-8')))


def generated(root, data):
    root = Path(root); result = {}
    for name in ['app/package.json', 'app/package-lock.json', 'app/src-tauri/tauri.conf.json']:
        obj = json.loads((root/name).read_text(encoding='utf-8'))
        obj['version'] = data['nativeVersion'] if name.endswith('tauri.conf.json') else data['version']
        if name.endswith('package-lock.json'): obj['packages']['']['version'] = data['version']
        result[name] = json.dumps(obj, ensure_ascii=False, indent=2) + '\n'
    for name in ['app/src-tauri/Cargo.toml', 'app/src-tauri/Cargo.lock']:
        content = (root/name).read_text(encoding='utf-8')
        pattern = r'(?m)(^name = "app"\nversion = ")[^"]+("$)'
        changed, count = re.subn(pattern, lambda m: m[1] + data['version'] + m[2], content)
        if count != 1: raise ValueError('无法唯一定位 app Cargo 版本：' + name)
        result[name] = changed
    properties = root/'app/src-tauri/gen/android/app/tauri.properties'
    if properties.exists():
        result[properties.relative_to(root).as_posix()] = (
            '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n'
            f"tauri.android.versionName={data['nativeVersion']}\n"
            f"tauri.android.versionCode={data['androidVersionCode']}\n")
    return result


def check(root=ROOT):
    root = Path(root); data = load(root); mismatches = []
    for name, expected in generated(root, data).items():
        actual = (root/name).read_text(encoding='utf-8')
        if name.endswith('.json'):
            same = json.loads(actual) == json.loads(expected)
        elif name.endswith('tauri.properties'):
            same = all(line in actual.splitlines() for line in expected.splitlines() if not line.startswith('//'))
        else: same = actual == expected
        if not same: mismatches.append(name)
    return mismatches


def sync(root=ROOT):
    root = Path(root); data = load(root)
    for name, content in generated(root, data).items(): (root/name).write_text(content, encoding='utf-8', newline='\n')
    return check(root)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('check')
    sub.add_parser('sync').add_argument('--apply', action='store_true')
    setter = sub.add_parser('set')
    setter.add_argument('--version', required=True)
    setter.add_argument('--android-version-code', type=int)
    setter.add_argument('--native-version', help='独立的递增安装版本；默认在需要时增加安装补丁号。')
    setter.add_argument('--apply', action='store_true')
    args = parser.parse_args(); data = load(args.root)
    if args.command == 'set':
        candidate = dict(data); candidate['version'] = args.version; candidate['tag'] = 'v' + args.version
        key = version_key(args.version)
        old_native=native_key(data['nativeVersion'])
        next_native=key[:3] if key[:3]>old_native else (old_native[0],old_native[1],old_native[2]+1) if args.version!=data['version'] else old_native
        candidate['nativeVersion'] = args.native_version or '.'.join(map(str,next_native))
        candidate['androidVersionCode'] = args.android_version_code if args.android_version_code is not None else max(
            key[0]*1_000_000 + key[1]*1_000 + key[2], data['androidVersionCode'] + int(args.version != data['version']))
        validate(candidate, previous=data)
        if args.apply:
            generated(args.root, candidate)  # Complete all parsing/preflight before the first write.
            (args.root/'release.json').write_text(json.dumps(candidate, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
            sync(args.root)
        print(json.dumps({'ok': True, 'applied': args.apply, 'release': candidate})); return 0
    mismatches = sync(args.root) if args.command == 'sync' and args.apply else check(args.root)
    print(json.dumps({'ok': not mismatches, 'mismatches': mismatches}))
    return int(bool(mismatches))


if __name__ == '__main__': raise SystemExit(main())
